param(
    [string]$OrgAlias = "DeveloperExerciseProject-ScratchOrg",
    [string]$DataFile = "data/test-data.json"
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
if (-not [System.IO.Path]::IsPathRooted($DataFile)) {
    $DataFile = Join-Path $root $DataFile
}

$data = Get-Content -LiteralPath $DataFile -Raw | ConvertFrom-Json

function Esc([string]$value) {
    if ($null -eq $value) { return "" }
    return $value.Replace("'", "''")
}

function ApexDate([string]$value) {
    $d = [datetime]::ParseExact($value, 'yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)
    return "Date.newInstance($($d.Year), $($d.Month), $($d.Day))"
}

function Num($value) {
    return [string]::Format([Globalization.CultureInfo]::InvariantCulture, "{0}", $value)
}

function Money($value) {
    $d = [decimal]$value
    return $d.ToString('0.00', [Globalization.CultureInfo]::InvariantCulture)
}

$lines = New-Object System.Collections.Generic.List[string]

$lines.Add("// Generated by scripts/load-test-data.ps1 from $([System.IO.Path]::GetFileName($DataFile)).")
$lines.Add("// Clears old TalentBridge test data, then loads the data in the repository file.")
$lines.Add("List<Account> existingAccounts = [SELECT Id FROM Account WHERE Name IN ('TV', 'MediCare Plus', 'EduCore', 'FinTrust')];")
$lines.Add("delete [SELECT Id FROM Hiring__c];")
$lines.Add("delete [SELECT Id FROM Position__c];")
$lines.Add("delete [SELECT Id FROM Consultant__c];")
$lines.Add("delete [SELECT Id FROM Contact WHERE AccountId IN :existingAccounts];")
$lines.Add("delete existingAccounts;")
$lines.Add("")

$empVars = @{}
$empVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.employers.Count; $i++) {
    $e = $data.employers[$i]
    $var = "emp$i"
    $empVars[$e.key] = $var
    $empVarList.Add($var)
    $lines.Add("Account $var = new Account(Name = '$(Esc $e.name)', Domain__c = '$(Esc $e.domain)');")
}
$lines.Add("insert new List<Account>{ $($empVarList -join ', ') };")
$lines.Add("")

$hrVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.employers.Count; $i++) {
    $e = $data.employers[$i]
    $hr = $e.hrContact
    $var = "hr$i"
    $hrVarList.Add($var)
    $lines.Add("Contact $var = new Contact(FirstName = '$(Esc $hr.firstName)', LastName = '$(Esc $hr.lastName)', Email = '$(Esc $hr.email)', AccountId = $($empVars[$e.key]).Id);")
}
$lines.Add("insert new List<Contact>{ $($hrVarList -join ', ') };")
for ($i = 0; $i -lt $data.employers.Count; $i++) {
    $e = $data.employers[$i]
    $lines.Add("$($empVars[$e.key]).HR_Contact__c = hr$i.Id;")
}
$lines.Add("update new List<Account>{ $($empVarList -join ', ') };")
$lines.Add("")

$conVars = @{}
$conVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.consultants.Count; $i++) {
    $c = $data.consultants[$i]
    $var = "con$i"
    $conVars[$c.key] = $var
    $conVarList.Add($var)
    $married = if ($c.married) { "true" } else { "false" }
    $lines.Add("Consultant__c $var = new Consultant__c(First_Name__c = '$(Esc $c.firstName)', Last_Name__c = '$(Esc $c.lastName)', DOB__c = $(ApexDate $c.dob), Gender__c = '$(Esc $c.gender)', Email__c = '$(Esc $c.email)', Married__c = $married, Education__c = '$(Esc $c.education)');")
}
$lines.Add("insert new List<Consultant__c>{ $($conVarList -join ', ') };")
$lines.Add("")

$posVars = @{}
$posVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.positions.Count; $i++) {
    $p = $data.positions[$i]
    $var = "pos$i"
    $posVars[$p.key] = $var
    $posVarList.Add($var)
    $lines.Add("Position__c $var = new Position__c(Name = '$(Esc $p.name)', Employer__c = $($empVars[$p.employer]).Id, Openings__c = $(Num $p.openings), Status__c = '$(Esc $p.status)', Hourly_Rate__c = $(Money $p.hourlyRate), Description__c = '$(Esc $p.description)');")
}
$lines.Add("insert new List<Position__c>{ $($posVarList -join ', ') };")
$lines.Add("")

$hirVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.hirings.Count; $i++) {
    $h = $data.hirings[$i]
    $var = "hir$i"
    $hirVarList.Add($var)
    $parts = @(
        "Employer__c = $($empVars[$h.employer]).Id",
        "Consultant__c = $($conVars[$h.consultant]).Id",
        "Hire_Date__c = $(ApexDate $h.hireDate)"
    )
    if (-not [string]::IsNullOrEmpty($h.position)) {
        $parts += "Position__c = $($posVars[$h.position]).Id"
    }
    $lines.Add("Hiring__c $var = new Hiring__c($($parts -join ', '));")
}
$lines.Add("insert new List<Hiring__c>{ $($hirVarList -join ', ') };")
$lines.Add("")
$lines.Add("System.debug('Loaded ' + $($data.employers.Count) + ' employers, ' + $($data.consultants.Count) + ' consultants, ' + $($data.positions.Count) + ' positions and ' + $($data.hirings.Count) + ' hirings.');")

$apexFile = Join-Path $PSScriptRoot '.generated-test-data.apex'
$apexNamedFile = Join-Path $PSScriptRoot 'apex\load-test-data.apex'
$fileContent = $lines -join "`r`n"
Set-Content -LiteralPath $apexFile -Value $fileContent -Encoding ASCII
Set-Content -LiteralPath $apexNamedFile -Value $fileContent -Encoding ASCII

Write-Host "Generated $apexFile and $apexNamedFile"
& sf apex run --file $apexFile --target-org $OrgAlias
if ($LASTEXITCODE -ne 0) {
    throw "Test data load failed with exit code $LASTEXITCODE"
}

Write-Host "Test data loaded into $OrgAlias"
